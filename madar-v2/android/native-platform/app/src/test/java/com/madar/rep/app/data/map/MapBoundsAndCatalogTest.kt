    @Test
    fun testDecodeStringBounds() {
        val jsonText = """{"bounds": "24.5,21.5,37.3,32.6"}"""
        val wrapper = json.decodeFromString<BoundsWrapper>(jsonText)
        assertNotNull(wrapper.bounds)
        assertEquals(24.5, wrapper.bounds!!.west, 1e-6)
        assertEquals(21.5, wrapper.bounds!!.south, 1e-6)
        assertEquals(37.3, wrapper.bounds!!.east, 1e-6)
        assertEquals(32.6, wrapper.bounds!!.north, 1e-6)
    }

    @Test
    fun testDecodeObjectBounds() {
        val jsonText = """{"bounds": {"west": 30.6, "south": 29.4, "east": 32.1, "north": 31.0}}"""
        val wrapper = json.decodeFromString<BoundsWrapper>(jsonText)
        assertNotNull(wrapper.bounds)
        assertEquals(30.6, wrapper.bounds!!.west, 1e-6)
        assertEquals(29.4, wrapper.bounds!!.south, 1e-6)
        assertEquals(32.1, wrapper.bounds!!.east, 1e-6)
        assertEquals(31.0, wrapper.bounds!!.north, 1e-6)
    }

    @Test
    fun testDecodeArrayBounds() {
        val jsonText = """{"bounds": [29.3, 29.0, 33.4, 32.0]}"""
        val wrapper = json.decodeFromString<BoundsWrapper>(jsonText)
        assertNotNull(wrapper.bounds)
        assertEquals(29.3, wrapper.bounds!!.west, 1e-6)
        assertEquals(29.0, wrapper.bounds!!.south, 1e-6)
        assertEquals(33.4, wrapper.bounds!!.east, 1e-6)
        assertEquals(32.0, wrapper.bounds!!.north, 1e-6)
    }

    @Test
    fun testRejectMalformedStringBounds() {
        val malformedCases = listOf(
            """{"bounds": "not-a-number,21.5,37.3,32.6"}""",
            """{"bounds": "24.5,21.5,37.3"}""", // only 3
            """{"bounds": "24.5,21.5,37.3,32.6,50.0"}""", // 5 values
            """{"bounds": "50.0,21.5,30.0,32.6"}""", // west > east (50 > 30)
            """{"bounds": "24.5,40.0,37.3,30.0"}""", // south > north (40 > 30)
            """{"bounds": "NaN,21.5,37.3,32.6"}""",
        )
        for (case in malformedCases) {
            try {
                json.decodeFromString<BoundsWrapper>(case)
                fail("Expected SerializationException for case: $case")
            } catch (e: SerializationException) {
                // Expected
                assertTrue(e.message?.isNotBlank() == true)
            }
        }
    }

