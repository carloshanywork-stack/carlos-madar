    @Test
    fun testRealManifestPayload() {
        val manifestPayload = """
        {
          "success": true,
          "pack": {
            "id": "greater-cairo",
            "name": "القاهرة الكبرى",
            "minZoom": 8,
            "maxZoom": 14,
            "bounds": "30.6,29.4,32.1,31",
            "coverageBounds": { "west": 30.6, "south": 29.4, "east": 32.1, "north": 31.0 },
            "available": true,
            "renderable": true,
            "tileCount": 1,
            "sizeBytes": 1024,
            "format": "png",
            "attribution": "© OSM",
            "license": "ODbL",
            "tiles": [
              { "z": 8, "x": 150, "y": 105, "sizeBytes": 1024 }
            ]
          }
        }
        """.trimIndent()

        val response = json.decodeFromString<MapManifestResponse>(manifestPayload)
        assertTrue(response.success)
        assertNotNull(response.pack)
        val pack = response.pack!!
        assertEquals("greater-cairo", pack.id)
        assertNotNull(pack.effectiveBounds)
        assertEquals(30.6, pack.effectiveBounds!!.west, 1e-6)
        assertEquals(1, pack.tiles.size)
        assertEquals(8, pack.tiles[0].z)
        assertEquals(150, pack.tiles[0].x)
        assertEquals(105, pack.tiles[0].y)
    }

    @Test
    fun testFallbackWhenCoverageBoundsIsMissing() {
        val legacyJson = """
        {
          "id": "legacy-pack",
          "name": "Legacy",
          "bounds": "30.0,29.0,32.0,31.0"
        }
        """.trimIndent()

        val pack = json.decodeFromString<MapPack>(legacyJson)
        assertNotNull(pack.bounds)
        assertNull(pack.coverageBounds)
        assertNotNull(pack.effectiveBounds)
        assertEquals(30.0, pack.effectiveBounds!!.west, 1e-6)
    }

    @kotlinx.serialization.Serializable
    private data class BoundsWrapper(val bounds: MapBounds? = null)
