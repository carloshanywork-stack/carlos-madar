import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const root = mkdtempSync(join(tmpdir(), 'madar-audit-gps-'));
Object.assign(process.env,{MADAR_V2_DATABASE_PATH:join(root,'db.sqlite'),MADAR_V2_DATA_DIR:root,MADAR_V2_STORAGE_ROOT:join(root,'storage'),MADAR_V2_BACKUP_ROOT:join(root,'backups'),MADAR_V2_OFFLINE_MAP_PATH:join(root,'map.mbtiles'),STORAGE_MOUNT_PATH:'',NODE_ENV:'test',MADAR_V2_JWT_SECRET:'isolated-audit-fixture-key-32-bytes-minimum'});
